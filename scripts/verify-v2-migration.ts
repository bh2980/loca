import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {copyFileSync,mkdtempSync,readFileSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {resolve,join} from 'node:path';
import {Engine} from '@workbench/core';
import {validateStudioStorage} from '../packages/core/src/studio-storage.ts';

const backupDir=resolve(process.argv[2]??'');
assert.ok(backupDir.startsWith(resolve('artifacts')+requireSep()),'Expected an artifacts backup directory');
function requireSep(){return process.platform==='win32'?'\\':'/';}
const manifest=JSON.parse(readFileSync(join(backupDir,'manifest.json'),'utf8'));
const clone=mkdtempSync(join(tmpdir(),'workbench-v2-migration-'));
copyFileSync(join(backupDir,'workbench.sqlite'),join(clone,'workbench.sqlite'));
const engine=new Engine(clone,{autoStart:false,invoke:async()=>{throw new Error('Migration must not invoke AI');}});
const hash=(value:unknown)=>createHash('sha256').update(JSON.stringify(value??null)).digest('hex');
const state=engine.state();validateStudioStorage(state);
const compared=Object.keys(manifest.hashes);
for(const field of compared)assert.equal(hash((state as unknown as Record<string,unknown>)[field]),manifest.hashes[field],`migration ${field}`);
for(const archived of manifest.archived)assert.equal(hash(engine.store.project(archived.id)),archived.hash,`archive ${archived.id}`);
const portable=engine.backupProject();
const restoreDir=mkdtempSync(join(tmpdir(),'workbench-v2-restore-'));
const restored=new Engine(restoreDir,{autoStart:false});
restored.restoreProject(portable);const result=restored.state();validateStudioStorage(result);
const portableFields=['project','units','groups','translations','terms','knowledge','graph'];
for(const field of portableFields)assert.equal(hash((result as unknown as Record<string,unknown>)[field]),hash((state as unknown as Record<string,unknown>)[field]),`restore ${field}`);
assert.deepEqual(result.studio,state.studio);
engine.close();restored.close();
const report={checkedAt:new Date().toISOString(),backupDir,clone,restoreDir,projectId:state.project.id,unitCount:state.units.length,compared,portableFields,archives:manifest.archived.map((v:{id:string})=>v.id),preserved:true,aiCalls:0};
writeFileSync('artifacts/v2-migration-verification.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report));
